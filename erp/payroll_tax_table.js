  const TEN_MILLION_TAX = [1560440,1484600,1251340,1221340,1191340,1161340,1131340,1101340,1071340,1041340,1011340];
  const DEFAULT_FAMILY_COUNT = 1;
  const DEFAULT_CHILD_COUNT = 0;
  const DEFAULT_WITHHOLDING_RATE = 1;
  const ALLOWED_WITHHOLDING_RATES = [0.8, 1, 1.2];

  function toFiniteNumber(value, fallback) {
    const numeric = Number(value);
    return Number.isFinite(numeric) ? numeric : fallback;
  }

  function floorTo10(value) {
    const numeric = Math.max(0, toFiniteNumber(value, 0));
    return Math.floor(numeric / 10) * 10;
  }

  function normalizeFamilyCount(value) {
    const numeric = Math.floor(toFiniteNumber(value, DEFAULT_FAMILY_COUNT));
    return Math.max(1, numeric);
  }

  function normalizeChildCount(value) {
    const numeric = Math.floor(toFiniteNumber(value, DEFAULT_CHILD_COUNT));
    return Math.max(0, numeric);
  }

  function normalizeWithholdingRate(value) {
    let numeric = toFiniteNumber(value, DEFAULT_WITHHOLDING_RATE);
    if (numeric > 2) numeric = numeric / 100;
    const match = ALLOWED_WITHHOLDING_RATES.find((rate) => Math.abs(rate - numeric) < 0.0001);
    return match || DEFAULT_WITHHOLDING_RATE;
  }

  function getFamilyTax(values, familyCount) {
    const count = normalizeFamilyCount(familyCount);
    const tableValues = Array.isArray(values) ? values : [];
    if (count <= 11) return Math.max(0, Math.round(toFiniteNumber(tableValues[count - 1], 0)));
    const tax10 = Math.max(0, Math.round(toFiniteNumber(tableValues[9], 0)));
    const tax11 = Math.max(0, Math.round(toFiniteNumber(tableValues[10], 0)));
    const delta = Math.max(0, tax10 - tax11);
    return Math.max(0, tax11 - (delta * (count - 11)));
  }

  function findTaxRowByIncome(monthlyIncome) {
    const income = Math.max(0, Math.floor(toFiniteNumber(monthlyIncome, 0)));
    if (income >= 10000000) return null;
    const incomeThousand = Math.floor(income / 1000);
    return TAX_ROWS.find((row) => incomeThousand >= row[0] && incomeThousand < row[1]) || null;
  }

  function getTableIncomeTax(monthlyIncome, familyCount) {
    const income = Math.max(0, Math.floor(toFiniteNumber(monthlyIncome, 0)));
    const normalizedFamilyCount = normalizeFamilyCount(familyCount);
    if (income < 1060000) return 0;
    if (income < 10000000) {
      const row = findTaxRowByIncome(income);
      return row ? getFamilyTax(row[2], normalizedFamilyCount) : 0;
    }

    const baseTax = getFamilyTax(TEN_MILLION_TAX, normalizedFamilyCount);
    if (income === 10000000) return baseTax;
    if (income <= 14000000) {
      return baseTax + ((income - 10000000) * 0.98 * 0.35);
    }
    return baseTax + 1372000 + ((income - 14000000) * 0.98 * 0.38);
  }

  function getChildTaxCredit(childCount) {
    const count = normalizeChildCount(childCount);
    if (count <= 0) return 0;
    if (count === 1) return 12500;
    if (count === 2) return 29160;
    return 29160 + ((count - 2) * 25000);
  }

  function calculate(options) {
    const source = options && typeof options === 'object' ? options : { monthlyIncome: options };
    const monthlyIncome = Math.max(0, Math.floor(toFiniteNumber(source.monthlyIncome, 0)));
    const familyCount = normalizeFamilyCount(source.familyCount);
    const childCount = normalizeChildCount(source.childCount);
    const withholdingRate = normalizeWithholdingRate(source.withholdingRate);
    const tableIncomeTax = floorTo10(getTableIncomeTax(monthlyIncome, familyCount));
    const childTaxCredit = Math.min(tableIncomeTax, getChildTaxCredit(childCount));
    const incomeTaxBeforeRate = Math.max(0, tableIncomeTax - childTaxCredit);
    const incomeTax = floorTo10(incomeTaxBeforeRate * withholdingRate);
    const localTax = floorTo10(incomeTax * 0.1);

    return {
      monthlyIncome,
      familyCount,
      childCount,
      withholdingRate,
      tableIncomeTax,
      childTaxCredit,
      incomeTaxBeforeRate,
      incomeTax,
      localTax
    };
  }

